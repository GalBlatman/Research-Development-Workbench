"""Gold-capable construction. Evaluators receive only the returned BlindPacket."""

import hashlib
import json

from domain.benchmark import (
    BenchmarkProject,
    BenchmarkVariant,
    BlindPacket,
    Feature,
    FrozenSplit,
    Mutation,
    Transformation,
    VisibleBlock,
)


def content_hash(value: object) -> str:
    if hasattr(value, "model_dump"):
        value = value.model_dump(mode="json")
    return hashlib.sha256(
        json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode()
    ).hexdigest()


def freeze(projects: tuple[BenchmarkProject, ...], version: str) -> FrozenSplit:
    return FrozenSplit(
        version=version,
        assignments=tuple(
            (p.benchmark_id, p.split, content_hash(p))
            for p in sorted(projects, key=lambda p: p.benchmark_id)
        ),
    )


def validate_import(project: BenchmarkProject, manifest: FrozenSplit) -> None:
    entry = next((a for a in manifest.assignments if a[0] == project.benchmark_id), None)
    if entry is None or entry[1] != project.split or entry[2] != content_hash(project):
        raise ValueError("Frozen split/package mismatch")


def construct(
    project: BenchmarkProject,
    mutation: Mutation,
    variant_id: str,
    manifest: FrozenSplit,
    prior: BenchmarkVariant | None = None,
) -> BenchmarkVariant:
    validate_import(project, manifest)
    known = {f for b in project.source_package.blocks for f in b.features}
    if not set(mutation.targets) <= known:
        raise ValueError("Unknown transformation feature")
    if project.route != "EXPLAIN" and set(mutation.targets) & {
        Feature.MECHANISM,
        Feature.PREDICTIONS,
    }:
        raise ValueError("EXPLAIN-only target requires EXPLAIN route")
    kind = mutation.transformation
    if kind == Transformation.HIDE and len(mutation.targets) != 1:
        raise ValueError("HIDE_FEATURE requires one target")
    if kind == Transformation.MULTIPLE and len(mutation.targets) < 2:
        raise ValueError("HIDE_MULTIPLE requires selected combination")
    if kind == Transformation.RESTORE:
        if (
            prior is None
            or prior.variant_id != mutation.parent_variant
            or prior.benchmark_id != project.benchmark_id
            or prior.split != project.split
            or prior.mutation.transformation
            not in (
                Transformation.HIDE,
                Transformation.MULTIPLE,
                Transformation.DEGRADE,
                Transformation.REVEAL,
            )
        ):
            raise ValueError("Restoration requires an authorized prior mutation")
        if set(mutation.targets) != set(prior.mutation.targets):
            raise ValueError("Restoration must name the previously affected features")
    removed = (
        set(mutation.targets)
        if kind in (Transformation.HIDE, Transformation.MULTIPLE, Transformation.DEGRADE)
        else set()
    )
    if kind == Transformation.REVEAL:
        if (
            len(set(mutation.reveal_order)) != len(mutation.reveal_order)
            or set(mutation.reveal_order) != set(mutation.targets)
            or mutation.reveal_count > len(mutation.reveal_order)
        ):
            raise ValueError("Invalid ordered reveal")
        removed = set(mutation.reveal_order[mutation.reveal_count :])
        if prior is not None and (
            prior.benchmark_id != project.benchmark_id
            or prior.split != project.split
            or prior.mutation.reveal_order != mutation.reveal_order
            or prior.mutation.reveal_count >= mutation.reveal_count
        ):
            raise ValueError("Reveal must progress monotonically")
    blocks = [b for b in project.source_package.blocks if not set(b.features) & removed]
    if kind == Transformation.DEGRADE:
        if not mutation.replacements or any(
            not set(b.features) <= set(mutation.targets) or not b.features
            for b in mutation.replacements
        ):
            raise ValueError("Degradation requires explicit feature-owned replacement")
        blocks.extend(mutation.replacements)
    elif mutation.replacements:
        if kind not in (Transformation.INTACT, Transformation.METADATA):
            raise ValueError("Replacements not allowed for this transformation")
        # Explicit administrator-certified equivalent anonymization, never generated by code.
        replacements = {b.block_id: b for b in mutation.replacements}
        if not replacements.keys() <= {b.block_id for b in blocks}:
            raise ValueError("Unknown anonymized block")
        blocks = [replacements.get(b.block_id, b) for b in blocks]
    visible = []
    for b in blocks:
        if b.metadata_only and not mutation.permit_metadata:
            continue
        text = b.text
        if not mutation.permit_metadata:
            for identity in sorted(
                project.source_package.identifying_metadata, key=len, reverse=True
            ):
                text = text.replace(identity, "[identifier removed]")
        if text.strip():
            visible.append(VisibleBlock(text=text, role=b.role))
    visibility = tuple(
        (
            f,
            any(
                f in b.features
                and b.block_id not in {r.block_id for r in mutation.replacements}
                and (not b.metadata_only or mutation.permit_metadata)
                for b in blocks
            ),
        )
        for f in sorted(known)
    )
    packet_data = {
        "route": project.route,
        "stage": project.stage,
        "blocks": [b.model_dump(mode="json") for b in visible],
    }
    packet = BlindPacket(
        packet_id=content_hash(packet_data),
        route=project.route,
        stage=project.stage,
        blocks=tuple(visible),
    )
    return BenchmarkVariant(
        variant_id=variant_id,
        benchmark_id=project.benchmark_id,
        split=project.split,
        version=project.version,
        mutation=mutation,
        visibility=visibility,
        packet=packet,
    )
